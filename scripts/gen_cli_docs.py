"""Write docs/CLI.md from the argparse parsers, so the CLI reference cannot drift.

Run: python scripts/gen_cli_docs.py          (rewrite docs/CLI.md)
     python scripts/gen_cli_docs.py --check  (exit 1 when docs/CLI.md is out of date)
"""

import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

OUT = ROOT / "docs" / "CLI.md"


def build() -> str:
    os.environ["COLUMNS"] = "100"  # a fixed width, so the output does not depend on the terminal
    from nexus_mcp import licensing, setup_clients
    from nexus_mcp.evaluate import cli

    data = cli._data_parser()
    parts = [
        "# CLI reference",
        "",
        "<!-- Generated by scripts/gen_cli_docs.py from the argparse parsers. Do not edit. -->",
        "",
        "`nexus-mcp-ci` with no arguments starts the MCP server over stdio. "
        "`python -m nexus_mcp` does the same.",
        "",
        "## nexus-mcp-ci eval",
        "",
        "```text",
        cli._eval_parser().format_help().rstrip(),
        "```",
        "",
        "## nexus-mcp-ci setup",
        "",
        "```text",
        setup_clients._parser().format_help().rstrip(),
        "```",
        "",
        "## nexus-mcp-ci license",
        "",
        "```text",
        licensing._parser().format_help().rstrip(),
        "```",
        "",
        "## nexus-mcp-ci data",
        "",
        "```text",
        data.format_help().rstrip(),
        "```",
    ]
    for action in data._subparsers._group_actions:
        for name, sub in action.choices.items():
            parts += ["", f"### nexus-mcp-ci data {name}", "", "```text"]
            parts += [sub.format_help().rstrip(), "```"]
    return "\n".join(parts) + "\n"


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    text = build()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("docs/CLI.md is out of date. Run: python scripts/gen_cli_docs.py")
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
